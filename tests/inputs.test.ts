// Incorrect and unusual setups: broken inputs, foreign files, hook managers,
// drift of every kind. Each must fail loudly (or warn) without writing.
import { describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { selfTest } from "../src/selftest";
import { ROOT, forge, git, sampleRepo, sh } from "./helpers";

const T = 120_000;

function put(repo: string, rel: string, text: string) {
  mkdirSync(join(repo, rel, ".."), { recursive: true });
  writeFileSync(join(repo, rel), text);
}

describe("invalid inputs stop apply and write nothing", () => {
  test.each([
    ["forge.yaml with an unknown key", "forge.yaml", 'forge: "0.5"\nextra: 1\n', /invalid project.*extra/],
    ["forge.yaml disable without a reason", "forge.yaml", 'forge: "0.5"\ndisable:\n  - id: pytest/run\n', /reason/],
    ["forge.yaml with a duplicate key", "forge.yaml", 'forge: "0.5"\nforge: "0.5"\n', /forge\.yaml/],
    ["forge.yaml with an alias", "forge.yaml", 'forge: &v "0.5"\npacks: {add: [*v]}\n', /alias|anchor/],
    ["forge.yaml without the version", "forge.yaml", "packs: {add: [zod]}\n", /forge/],
    ["a local rule with an unknown target", ".forge/rules/x.yaml", "id: local/x\ndescription: x\nscope: {language: any}\nenforce: [{target: shell, run: x}]\n", /\.forge\/rules\/x\.yaml/],
    ["a local rule with a bad id", ".forge/rules/x.yaml", "id: NotAnId\ndescription: x\nscope: {language: any}\nenforce: [{target: guard, decision: deny, pattern: x}]\n", /id/],
    ["settings.json that is not JSON", ".claude/settings.json", "{ not json", /\.claude\/settings\.json.*not valid JSON/],
    ["settings.json with permissions.ask not an array", ".claude/settings.json", '{"permissions": {"ask": "Edit(x)"}}', /not an array/],
  ])(
    "%s",
    (_name, rel, text, message) => {
      const repo = sampleRepo("fastapi-app");
      put(repo, rel, text);
      const r = forge(["apply", "--yes"], repo);
      expect(r.status).toBe(1);
      expect(r.stderr).toMatch(message);
      expect(existsSync(join(repo, ".forge", "forge.lock.json"))).toBe(false);
      expect(existsSync(join(repo, ".forge", "check.sh"))).toBe(false);
    },
    T,
  );

  test("outside a git repository", () => {
    const dir = mkdtempSync(join(tmpdir(), "forge-nogit-"));
    const r = forge(["apply", "--yes"], dir);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("not inside a git repository");
  });

  test("Claude Code missing", () => {
    const repo = sampleRepo("eslint-app");
    const bin = mkdtempSync(join(tmpdir(), "forge-noclaude-"));
    symlinkSync(process.execPath.includes("bun") ? sh("sh", ["-c", "command -v node"]).stdout.trim() : process.execPath, join(bin, "node"));
    const r = forge(["apply", "--yes"], repo, { PATH: `${bin}:/usr/bin:/bin` });
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("Claude Code not found");
    expect(existsSync(join(repo, ".forge"))).toBe(false);
  });

  test("unknown command and option", () => {
    expect(forge(["frobnicate"], ROOT).status).toBe(2);
    expect(forge(["apply", "--nope"], ROOT).status).toBe(2);
    expect(forge(["apply", "--user", "--local"], ROOT).status).toBe(2);
  });

  test("non-interactive settings change without --yes is refused", () => {
    const repo = sampleRepo("eslint-app");
    const r = forge(["apply"], repo);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("--yes");
    expect(existsSync(join(repo, ".claude", "settings.json"))).toBe(false);
  });
});

describe("warnings that do not stop apply", () => {
  test(
    "unknown packs and disables of inactive rules are reported",
    () => {
      const repo = sampleRepo("eslint-app");
      put(repo, "forge.yaml", 'forge: "0.5"\npacks: {add: [nosuch, safety]}\ndisable:\n  - {id: pytest/run, reason: not here}\n');
      const r = forge(["apply", "--yes"], repo);
      expect(r.status).toBe(0);
      expect(r.stderr).toContain('unknown pack "nosuch"');
      expect(r.stderr).toContain('"safety" is a user-level pack');
      expect(r.stderr).toContain('rule "pytest/run" is not active here');
    },
    T,
  );
});

describe("foreign and drifted files", () => {
  test(
    "an unowned file at an owned path stops apply; --force replaces it",
    () => {
      const repo = sampleRepo("eslint-app");
      put(repo, ".forge/check.sh", "#!/bin/sh\necho mine\n");
      const r = forge(["apply", "--yes"], repo);
      expect(r.status).toBe(1);
      expect(r.stderr).toContain(".forge/check.sh exists and is not a forge file");
      expect(readFileSync(join(repo, ".forge/check.sh"), "utf8")).toBe("#!/bin/sh\necho mine\n");
      expect(forge(["apply", "--yes", "--force"], repo).status).toBe(0);
      expect(readFileSync(join(repo, ".forge/check.sh"), "utf8")).toContain("Generated by forge");
    },
    T,
  );

  test(
    "a deleted owned file is recreated without --force; check.sh reports it first",
    () => {
      const repo = sampleRepo("eslint-app");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      rmSync(join(repo, ".claude/skills/forge-project/scripts/stop.sh"));
      const c = sh("sh", [".forge/check.sh", "--changed"], { cwd: repo });
      expect(c.stdout).toContain("forge:forge/integrity .claude/skills/forge-project/scripts/stop.sh is missing");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      expect(existsSync(join(repo, ".claude/skills/forge-project/scripts/stop.sh"))).toBe(true);
    },
    T,
  );

  test(
    "a removed settings entry is reported by diff/status and re-added by apply",
    () => {
      const repo = sampleRepo("eslint-app");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      const f = join(repo, ".claude/settings.json");
      writeFileSync(f, readFileSync(f, "utf8").replace('"Edit(forge.yaml)",', ""));
      const d = forge(["diff"], repo);
      expect(d.status).toBe(1);
      expect(d.stdout).toContain('entry missing, apply re-adds it: permissions.ask "Edit(forge.yaml)"');
      expect(forge(["status"], repo).stdout).toContain('missing permissions.ask "Edit(forge.yaml)"');
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      expect(readFileSync(f, "utf8")).toContain("Edit(forge.yaml)");
    },
    T,
  );

  test(
    "a rule whose source changed since the last apply is reported",
    () => {
      const repo = sampleRepo("eslint-app");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      const lockFile = join(repo, ".forge/forge.lock.json");
      const lock = JSON.parse(readFileSync(lockFile, "utf8"));
      lock.rules["typescript/strict"] = "0".repeat(64);
      writeFileSync(lockFile, JSON.stringify(lock, null, 2) + "\n");
      expect(forge(["diff"], repo).stdout).toContain("rule typescript/strict changed since the last apply");
      expect(forge(["status"], repo).stdout).toContain("rule typescript/strict changed since the last apply");
    },
    T,
  );

  test(
    "user entries already in settings are kept and never recorded",
    () => {
      const repo = sampleRepo("eslint-app");
      put(repo, ".claude/settings.json", '{\n  // team settings\n  "permissions": {"ask": ["Edit(.forge/**)"], "allow": ["Bash(ls:*)"]}\n}\n');
      git(repo, "add", "-A");
      git(repo, "commit", "-qm", "settings");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      const lock = JSON.parse(readFileSync(join(repo, ".forge/forge.lock.json"), "utf8"));
      expect(lock.settings.map((e: { value: string }) => e.value)).not.toContain("Edit(.forge/**)");
      expect(forge(["remove", "--yes"], repo).status).toBe(0);
      const back = readFileSync(join(repo, ".claude/settings.json"), "utf8");
      expect(back).toContain("// team settings");
      expect(back).toContain("Edit(.forge/**)");
      expect(back).toContain("Bash(ls:*)");
      expect(back).not.toContain("Edit(forge.yaml)");
    },
    T,
  );
});

describe("pre-commit (§10.3)", () => {
  test.each([[".husky"], ["lefthook.yml"], [".pre-commit-config.yaml"]])(
    "with %s: no hook created, status prints the line to add",
    (manager) => {
      const repo = sampleRepo("eslint-app");
      if (manager === ".husky") mkdirSync(join(repo, ".husky"));
      else put(repo, manager, "# hooks\n");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      expect(existsSync(join(repo, ".git/hooks/pre-commit"))).toBe(false);
      expect(forge(["status"], repo).stdout).toContain(`add "sh .forge/check.sh --changed" to ${manager}`);
    },
    T,
  );

  test(
    "core.hooksPath set: no hook created",
    () => {
      const repo = sampleRepo("eslint-app");
      git(repo, "config", "core.hooksPath", "githooks");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      expect(existsSync(join(repo, ".git/hooks/pre-commit"))).toBe(false);
      expect(forge(["status"], repo).stdout).toContain("core.hooksPath (githooks)");
    },
    T,
  );

  test(
    "an existing pre-commit hook is never touched",
    () => {
      const repo = sampleRepo("eslint-app");
      put(repo, ".git/hooks/pre-commit", "#!/bin/sh\necho mine\n");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      expect(readFileSync(join(repo, ".git/hooks/pre-commit"), "utf8")).toBe("#!/bin/sh\necho mine\n");
      expect(forge(["remove", "--yes"], repo).status).toBe(0);
      expect(readFileSync(join(repo, ".git/hooks/pre-commit"), "utf8")).toBe("#!/bin/sh\necho mine\n");
    },
    T,
  );

  test(
    "the created hook runs check.sh and blocks a bad commit",
    () => {
      const repo = sampleRepo("eslint-app");
      expect(forge(["apply", "--yes"], repo).status).toBe(0);
      git(repo, "add", "-A");
      expect(git(repo, "commit", "-qm", "forge").status).toBe(0);
      put(repo, "src/bad.ts", "export const x = 1 as any;\n");
      git(repo, "add", "-A");
      const r = git(repo, "commit", "-qm", "bad");
      expect(r.status).not.toBe(0);
      expect(r.stdout + r.stderr).toContain("forge:typescript/no-explicit-any src/bad.ts");
    },
    T,
  );
});

describe("forge test catches broken packs", () => {
  function packsWith(files: Record<string, string>): string {
    const dir = mkdtempSync(join(tmpdir(), "forge-packs-"));
    for (const [rel, text] of Object.entries({ "demo/pack.yaml": "id: demo\ndescription: Demo.\nlevel: project\n", ...files })) {
      mkdirSync(join(dir, rel, ".."), { recursive: true });
      writeFileSync(join(dir, rel), text);
    }
    return dir;
  }
  const guardRule = (match: string, noMatch: string) =>
    `id: demo/g\ndescription: Demo guard.\nscope: {language: any}\nenforce: [{target: guard, decision: deny, pattern: "rm[[:space:]]+-rf"}]\nexamples: {match: [${JSON.stringify(match)}], no_match: [${JSON.stringify(noMatch)}]}\n`;

  test("a correct pack passes", () => {
    expect(selfTest(packsWith({ "demo/rules/g.yaml": guardRule("rm -rf x", "rm x") })).failures).toEqual([]);
  });
  test("a guard example that does not trigger", () => {
    const f = selfTest(packsWith({ "demo/rules/g.yaml": guardRule("rm -r x", "rm x") })).failures;
    expect(f.some((x) => x.includes('demo/g [sh]: expected deny for "rm -r x", got nothing'))).toBe(true);
  });
  test("a guard no_match example that triggers", () => {
    const f = selfTest(packsWith({ "demo/rules/g.yaml": guardRule("rm -rf x", "rm -rf y") })).failures;
    expect(f.some((x) => x.includes('expected nothing for "rm -rf y"'))).toBe(true);
  });
  test("a permission example that no rule matches", () => {
    const rule = 'id: demo/p\ndescription: P.\nscope: {language: any}\nenforce: [{target: permission, decision: deny, rule: "Bash(git clean:*)"}]\nexamples: {match: ["Bash(git cleanup)"], no_match: ["Bash(ls)"]}\n';
    expect(selfTest(packsWith({ "demo/rules/p.yaml": rule })).failures).toContain("demo/p: no permission rule matches Bash(git cleanup)");
  });
  test(
    "an ast-grep rule whose examples fail",
    () => {
      const rule = 'id: demo/a\ndescription: A.\nscope: {language: python}\nenforce: [{target: ast-grep, mode: forbid, rule: {pattern: "eval($$$)"}}]\nexamples: {match: ["exec(x)"], no_match: ["print(x)"]}\n';
      const f = selfTest(packsWith({ "demo/rules/a.yaml": rule })).failures;
      expect(f.some((x) => x.startsWith("ast-grep test failed") && x.includes("demo/a"))).toBe(true);
    },
    T,
  );
  test("context.md over 10 lines", () => {
    const f = selfTest(packsWith({ "demo/context.md": "line\n".repeat(11) })).failures;
    expect(f).toContain("demo/context.md: 11 lines (max 10)");
  });
  test("rule id not matching its file name", () => {
    const f = selfTest(packsWith({ "demo/rules/other.yaml": guardRule("rm -rf x", "rm x") })).failures;
    expect(f[0]).toContain('id must be "demo/other"');
  });
  test("a rule without examples", () => {
    const rule = 'id: demo/n\ndescription: N.\nscope: {language: any}\nenforce: [{target: guard, decision: ask, pattern: "x"}]\n';
    expect(selfTest(packsWith({ "demo/rules/n.yaml": rule })).failures).toContain("demo/n: needs match and no_match examples");
  });
  test("a pack requiring an unknown pack", () => {
    const f = selfTest(packsWith({ "demo/pack.yaml": "id: demo\ndescription: D.\nlevel: project\nrequires: [ghost]\n" })).failures;
    expect(f[0]).toContain("requires unknown pack ghost");
  });
  test("a user-level pack with detect", () => {
    const f = selfTest(packsWith({ "demo/pack.yaml": "id: demo\ndescription: D.\nlevel: user\ndetect: {files_any: [x]}\n" })).failures;
    expect(f[0]).toContain("invalid pack");
  });
});
