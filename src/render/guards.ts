import type { GuardTarget, Rule } from "../types.js";

export interface ActiveGuard {
  rule: Rule;
  target: GuardTarget;
}

export function ruleSource(rule: Rule, base: string): string {
  if (rule.origin === "local") return rule.file.startsWith(base + "/") ? rule.file.slice(base.length + 1) : rule.file;
  return `packs/${rule.pack}/rules/${rule.file.split("/").pop()}`;
}

/**
 * Literal texts one of which every match of a POSIX ERE contains ([] when the pattern has
 * no such set): guard.sh tests them with index() before compiling the pattern, so the rules
 * a command cannot match cost no regex. A top-level alternation gives the union of its
 * branches' sets; in a sequence, a run of plain characters gives one text and a required
 * group (not followed by ?, * or {0) its own set; the smallest set with the longest texts
 * is kept. Bracket expressions, `.`, anchors and quantified characters end a run.
 */
export function requiredLiterals(re: string): string[] {
  // the top-level branches of re
  const branches: string[] = [];
  let depth = 0;
  let from = 0;
  for (let i = 0; i < re.length; i++) {
    const c = re[i];
    if (c === "\\") i++;
    else if (c === "[") i = bracketEnd(re, i);
    else if (c === "(") depth++;
    else if (c === ")") depth--;
    else if (c === "|" && depth === 0) {
      branches.push(re.slice(from, i));
      from = i + 1;
    }
  }
  branches.push(re.slice(from));
  if (branches.length > 1) {
    const sets = branches.map(requiredLiterals);
    return sets.some((x) => !x.length) ? [] : [...new Set(sets.flat())];
  }
  const candidates: string[][] = [];
  let cur = "";
  const flush = () => {
    if (cur) candidates.push([cur]);
    cur = "";
  };
  const optional = (i: number) => re[i] === "?" || re[i] === "*" || (re[i] === "{" && /^\{0[,}]/.test(re.slice(i)));
  const skipQuantifier = (i: number) => (re[i] === "{" ? re.indexOf("}", i) : /[?*+]/.test(re[i] ?? "") ? i : i - 1);
  for (let i = 0; i < re.length; i++) {
    const c = re[i]!;
    if (c === "[") {
      flush();
      i = skipQuantifier(bracketEnd(re, i) + 1);
      continue;
    }
    if (c === "(") {
      flush();
      let d = 1;
      let j = i + 1;
      for (; j < re.length && d > 0; j++) {
        if (re[j] === "\\") j++;
        else if (re[j] === "[") j = bracketEnd(re, j);
        else if (re[j] === "(") d++;
        else if (re[j] === ")") d--;
      }
      // j is past the closing parenthesis
      if (!optional(j)) {
        const inner = requiredLiterals(re.slice(i + 1, j - 1));
        if (inner.length) candidates.push(inner);
      }
      i = skipQuantifier(j);
      continue;
    }
    let lit: string | undefined;
    if (c === "\\") lit = re[++i];
    else if (!".^$*+?{}()|".includes(c)) lit = c;
    if (lit === undefined) {
      flush();
      if (c === "{") i = re.indexOf("}", i);
      continue;
    }
    if (optional(i + 1)) {
      flush();
      i = skipQuantifier(i + 1);
    } else if (re[i + 1] === "+" || re[i + 1] === "{") {
      cur += lit;
      flush();
      i = skipQuantifier(i + 1);
    } else cur += lit;
  }
  flush();
  // fewest alternatives, then the longest shortest text
  const score = (x: string[]) => [x.length, -Math.min(...x.map((t) => t.length))];
  candidates.sort((a, b) => score(a)[0]! - score(b)[0]! || score(a)[1]! - score(b)[1]!);
  const best = candidates[0];
  return best && Math.min(...best.map((t) => t.length)) >= 2 ? best : [];
}

/** The index of the ] closing the bracket expression that opens at i. */
export function bracketEnd(re: string, i: number): number {
  let j = i + 1;
  if (re[j] === "^") j++;
  if (re[j] === "]") j++;
  for (; j < re.length && re[j] !== "]"; j++) if (re[j] === "[" && /[:.=]/.test(re[j + 1] ?? "")) j = re.indexOf(`${re[j + 1]}]`, j + 2) + 1;
  return j;
}

export function renderGuardRules(guards: ActiveGuard[], base: string): string {
  const sources = [...new Set(guards.map((g) => ruleSource(g.rule, base)))].sort();
  const lines = [
    "# Generated by forge. Do not edit; changes are detected by the integrity check.",
    "# Columns (tab-separated): id, decision, pattern (POSIX ERE on the JSON-escaped command), description, check (a guard.sh check deciding when the pattern matches), review (the question a reviewer answers), then literals (every match contains one of them: tested before the pattern).",
    `# Sources: ${sources.length ? sources.join(", ") : "none"}`,
  ];
  const ordered = [...guards.filter((g) => g.target.decision === "deny"), ...guards.filter((g) => g.target.decision === "ask")];
  for (const g of ordered) {
    const cols = [g.rule.id, g.target.decision, g.target.pattern, g.rule.description];
    const literals = requiredLiterals(g.target.pattern);
    if (g.target.check || g.rule.review || literals.length) cols.push(g.target.check ?? "");
    if (g.rule.review || literals.length) cols.push(g.rule.review ?? "");
    cols.push(...literals);
    lines.push(cols.join("\t"));
  }
  return lines.join("\n") + "\n";
}
