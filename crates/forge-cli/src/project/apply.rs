//! `forge apply`, `forge diff` and `forge init`.

use forge_packs::model::{Level, PackSource};
use forge_render::changes::{Changes, line_diff};
use forge_render::report::{ToolProbe, audit_rules, format_audit};

use super::io::{Error, confirm, delete_path, prune_dirs, show_diff, write_settings, write_text};
use super::{Ctx, Flags, claude_gate, context, person_notes, precommit};

/// Prints what apply would change. Returns whether anything differs.
pub fn print_diff(ctx: &Ctx, ch: &Changes) -> bool {
    let mut any = false;
    for w in &ch.writes {
        let label = if w.before.is_none() {
            format!("{} (new)", w.path)
        } else {
            w.path.clone()
        };
        print!(
            "{}",
            line_diff(w.before.as_deref().unwrap_or(""), &w.after, &label)
        );
        any = true;
    }
    for d in &ch.deletes {
        println!("--- {d} (deleted)");
        any = true;
    }
    for b in &ch.blocks {
        show_diff(b.before.as_deref(), Some(&b.after), &b.path);
        any = true;
    }
    for s in &ch.settings {
        show_diff(Some(&s.before), s.after.as_deref(), &s.file);
        any = true;
    }
    for d in &ch.old_deletes {
        println!("--- {d} (deleted: generated by forge 0.5)");
        any = true;
    }
    for e in &ch.missing_entries {
        println!(
            "forge: {}: entry missing, apply re-adds it: {} {}",
            e.file, e.path, e.value
        );
    }
    for id in &ch.rules_changed {
        println!("forge: rule {id} changed since the last apply");
    }
    for r in &ch.roles_changed {
        println!("forge: {r}");
    }
    if ch.lock_changed {
        let before =
            std::fs::read_to_string(ctx.base.join(&ctx.plan.lock_path)).unwrap_or_default();
        print!("{}", line_diff(&before, &ch.lock_text, &ctx.plan.lock_path));
        any = true;
    }
    any || !ch.missing_entries.is_empty()
        || !ch.rules_changed.is_empty()
        || !ch.roles_changed.is_empty()
}

pub fn diff(flags: &Flags) -> Result<u8, Error> {
    let ctx = context(flags)?;
    let ch = ctx.changes()?;
    for p in &ch.drift {
        println!("forge: {p} was modified since the last apply");
    }
    for p in &ch.conflicts {
        println!("forge: {p} exists and is not a forge file");
    }
    let differs = print_diff(&ctx, &ch);
    Ok(u8::from(differs || !ch.drift.is_empty()))
}

pub fn apply(flags: &Flags, probe: &dyn ToolProbe) -> Result<u8, Error> {
    claude_gate()?;
    let mut ctx = context(flags)?;
    for w in &ctx.plan.warnings {
        eprintln!("forge: {w}");
    }
    let mut ch = ctx.changes()?;
    let stuck = !ch.drift.is_empty() || !ch.conflicts.is_empty() || !ch.old_modified.is_empty();
    if stuck && !flags.force {
        let read = |p: &str| std::fs::read_to_string(ctx.base.join(p)).ok();
        for p in &ch.drift {
            eprintln!("forge: {p} was modified since the last apply");
            show_diff(
                read(p).as_deref(),
                ctx.plan.files.get(p).map(String::as_str),
                p,
            );
        }
        for p in &ch.conflicts {
            eprintln!("forge: {p} exists and is not a forge file");
            show_diff(
                read(p).as_deref(),
                ctx.plan.files.get(p).map(String::as_str),
                p,
            );
        }
        for p in &ch.old_modified {
            eprintln!("forge: {p} (generated by forge 0.5) was modified since; apply deletes it");
        }
        eprintln!("forge: stopped. Re-run with --force to overwrite, or move the files away.");
        return Ok(1);
    }
    if flags.dry_run {
        print_diff(&ctx, &ch);
        return Ok(0);
    }
    let mut old: Vec<String> = ch.old_deletes.clone();
    old.extend(ch.old_modified.iter().cloned());
    if !old.is_empty() {
        println!(
            "forge: this repository has the layout of forge 0.5; moving to the new one deletes what forge generated there:"
        );
        for p in &old {
            println!("  {p}");
        }
        println!("  (kept: forge.yaml, .forge/rules/, .forge/packs/)");
        if !confirm("delete them?", flags.yes)? {
            return Err(Error::new("forge: cancelled; nothing written"));
        }
    }
    for s in ch.settings.iter().filter(|s| s.shared) {
        show_diff(Some(&s.before), s.after.as_deref(), &s.file);
        if !confirm(&format!("apply these changes to {}?", s.file), flags.yes)? {
            return Err(Error::new("forge: cancelled; nothing written"));
        }
    }
    if precommit::offer(&mut ctx, flags)? {
        ch = ctx.changes()?;
    }
    write(&ctx, &ch)?;
    if ctx.level == Level::Project {
        provision(&ctx);
    }
    for o in &ch.overridden {
        eprintln!("forge: {o}");
    }
    if ch.any() {
        println!(
            "forge: applied ({} written, {} deleted, {} settings file(s) updated)",
            ch.writes.len() + ch.blocks.len(),
            ch.deletes.len() + ch.old_deletes.len(),
            ch.settings.len()
        );
    } else {
        println!("forge: up to date");
    }
    report(&ctx, probe);
    Ok(0)
}

/// Installs the tools the lock pins that this setup uses: uv (Forge's PATH directory for the
/// agent) and the pinned tools the active checks and the types engine run. For the person.
fn provision(ctx: &Ctx) {
    let mut names = vec!["uv".to_string()];
    names.extend(forge_check::probe::pinned_tools(&ctx.plan));
    let report = crate::provisioning::ensure_tools(&names);
    let installed: Vec<String> = report
        .tools
        .iter()
        .filter(|t| t.installed_now)
        .map(|t| format!("{} {}", t.name, t.version))
        .collect();
    if !installed.is_empty() {
        println!("forge: installed {}", installed.join(", "));
    }
    for n in &report.notes {
        println!("forge: note: {n}");
    }
}

fn write(ctx: &Ctx, ch: &Changes) -> Result<(), Error> {
    let base = &ctx.base;
    for w in &ch.writes {
        let exec = w.path.ends_with("/pre-commit") && w.after.starts_with("#!");
        write_text(&base.join(&w.path), &w.after, exec)?;
    }
    for b in &ch.blocks {
        let yaml = b.path.ends_with(".yml") || b.path.ends_with(".yaml");
        write_text(&base.join(&b.path), &b.after, b.created && !yaml)?;
    }
    for d in &ch.deletes {
        delete_path(base, d)?;
    }
    for s in &ch.settings {
        write_settings(base, &s.file, s.after.as_deref())?;
    }
    if !ch.old_modified.is_empty() || !ch.old_deletes.is_empty() {
        for d in ch.old_modified.iter().chain(&ch.old_deletes) {
            delete_path(base, d)?;
        }
    }
    write_text(&base.join(&ctx.plan.lock_path), &ch.lock_text, false)?;
    if ctx.level == Level::Project {
        prune_dirs(&base.join(".forge"), base);
    }
    Ok(())
}

/// What apply tells the person after writing: audits, the commit-time check, missing tools,
/// what tool versions cannot do, notes. Machine state: never in the rules files.
fn report(ctx: &Ctx, probe: &dyn ToolProbe) {
    if ctx.level == Level::Project {
        for a in audit_rules(&ctx.plan, probe)
            .iter()
            .filter(|a| a.status == forge_render::report::AuditStatus::Unsatisfied)
        {
            println!("{}", format_audit(a));
        }
        let pre = precommit::state(ctx);
        if pre.activate.is_some() {
            println!("forge: pre-commit: {}", precommit::not_checked(ctx, &pre));
        } else if !pre.installed {
            println!(
                "forge: pre-commit: not installed, so commits are not checked; {}",
                precommit::hint(ctx)
            );
        }
    }
    let missing = probe.missing_tools(&ctx.plan);
    if !missing.is_empty() {
        println!(
            "forge: missing tools (checks using them are skipped): {}",
            missing.join(", ")
        );
    }
    let versions = probe.tool_versions(&ctx.plan);
    if !versions.is_empty() {
        println!("forge: tool versions (what they cannot do is not enforced):");
        for v in versions {
            println!("  {v}");
        }
    }
    for n in person_notes(ctx, probe) {
        println!("forge: note: {n}");
    }
}

/// `forge init`: the active packs' `init/` templates that do not exist yet, then apply.
pub fn init(flags: &Flags, probe: &dyn ToolProbe) -> Result<u8, Error> {
    if flags.user {
        return Err(Error::usage("forge: init is project-level only"));
    }
    claude_gate()?;
    let ctx = context(flags)?;
    if ctx.lock.is_some() || ctx.migration.is_some() {
        return Err(Error::new(
            "forge: init is for new projects; this one already has forge (use forge apply)",
        ));
    }
    for pk in &ctx.plan.packs {
        let pack = &ctx.set.packs[&pk.id];
        let Some(dir) = &pack.init_dir else { continue };
        for (rel, bytes) in init_files(pack.source, &ctx.base, dir) {
            let dest = ctx.base.join(&rel);
            if dest.exists() {
                println!("forge: {rel} exists, kept");
            } else if flags.dry_run {
                println!("forge: would create {rel} (from {})", pk.id);
            } else {
                let text = String::from_utf8_lossy(&bytes).into_owned();
                let text = switch_offs(&rel, &text, &ctx).unwrap_or(text);
                write_text(&dest, &text, false)?;
                println!("forge: created {rel} (from {})", pk.id);
            }
        }
    }
    apply(flags, probe)
}

/// The files of an `init/` directory: path below it → content, sorted.
fn init_files(source: PackSource, base: &std::path::Path, dir: &str) -> Vec<(String, Vec<u8>)> {
    let mut out = Vec::new();
    match source {
        PackSource::Builtin => {
            fn walk(d: &include_dir::Dir<'static>, root: &str, out: &mut Vec<(String, Vec<u8>)>) {
                for f in d.files() {
                    let p = f.path().to_string_lossy().replace('\\', "/");
                    if let Some(rel) = p.strip_prefix(root) {
                        out.push((rel.to_string(), f.contents().to_vec()));
                    }
                }
                for sub in d.dirs() {
                    walk(sub, root, out);
                }
            }
            if let Some(d) = forge_packs::BUILTIN_PACKS.get_dir(dir) {
                walk(d, &format!("{dir}/"), &mut out);
            }
        }
        PackSource::Local => {
            fn walk(d: &std::path::Path, rel: &str, out: &mut Vec<(String, Vec<u8>)>) {
                let Ok(rd) = std::fs::read_dir(d) else { return };
                for e in rd.flatten() {
                    let name = e.file_name().to_string_lossy().into_owned();
                    let r = if rel.is_empty() {
                        name
                    } else {
                        format!("{rel}/{name}")
                    };
                    if e.path().is_dir() {
                        walk(&e.path(), &r, out);
                    } else if let Ok(b) = std::fs::read(e.path()) {
                        out.push((r, b));
                    }
                }
            }
            walk(&base.join(dir), "", &mut out);
        }
    }
    out.sort();
    out
}

/// An init template with the diagnostics active packs switch off set to "off" (Biome's
/// `linter.rules.<group>.<name>`); `None` when none concerns it.
fn switch_offs(file: &str, text: &str, ctx: &Ctx) -> Option<String> {
    let name = file.rsplit('/').next().unwrap_or(file);
    if name != "biome.json" && name != "biome.jsonc" {
        return None;
    }
    let mine: Vec<_> = ctx
        .plan
        .switched_off
        .iter()
        .filter(|o| o.tool == "biome")
        .collect();
    if mine.is_empty() {
        return None;
    }
    let mut out = text.to_string();
    for o in mine {
        let parts: Vec<&str> = o.expects.split('/').collect();
        if parts.len() < 3 {
            continue;
        }
        out = forge_render::settings::set_value(
            &out,
            &["linter", "rules", parts[1], parts[2]],
            &serde_json::Value::String("off".into()),
        )
        .ok()?;
    }
    Some(out)
}
