/// Prints what apply would change. Returns whether anything differs.
pub fn print_diff(ctx: &Ctx, ch: &Changes) -> bool {
    let mut any = false;
    let show = |rel: &str| display_path(ctx.level, &ctx.base, rel);
    for w in &ch.writes {
        let label = if w.before.is_none() {
            format!("{} (new)", show(&w.path))
        } else {
            show(&w.path)
        };
        print!(
            "{}",
            line_diff(w.before.as_deref().unwrap_or(""), &w.after, &label)
        );
        any = true;
    }
    for d in &ch.deletes {
        println!("--- {} (deleted)", show(d));
        any = true;
    }
    for b in &ch.blocks {
        show_diff(b.before.as_deref(), Some(&b.after), &show(&b.path));
        any = true;
    }
    for s in &ch.settings {
        show_diff(Some(&s.before), s.after.as_deref(), &show(&s.file));
        any = true;
    }
    for d in &ch.old_deletes {
        println!("--- {} (deleted: generated by forge 0.5)", show(d));
        any = true;
    }
    for e in &ch.missing_entries {
        println!(
            "forge: {}: entry missing, apply re-adds it: {} {}",
            show(&e.file),
            e.path,
            e.value
        );
    }
    for id in &ch.rules_changed {
        println!("forge: rule {id} changed since the last apply");
    }
    for r in &ch.roles_changed {
        println!("forge: {r}");
    }
    if ch.lock_changed {
        let before =
            std::fs::read_to_string(ctx.base.join(&ctx.plan.lock_path)).unwrap_or_default();
        print!(
            "{}",
            line_diff(&before, &ch.lock_text, &show(&ctx.plan.lock_path))
        );
        any = true;
    }
    any || !ch.missing_entries.is_empty()
        || !ch.rules_changed.is_empty()
        || !ch.roles_changed.is_empty()
}

pub fn diff(flags: &Flags) -> Result<u8, Error> {
    let ctx = context(flags)?;
    let ch = ctx.changes()?;
    for p in &ch.drift {
        println!("forge: {p} was modified since the last apply");
    }
    for p in &ch.conflicts {
        println!("forge: {p} exists and is not a forge file");
    }
    let differs = print_diff(&ctx, &ch);
    Ok(u8::from(differs || !ch.drift.is_empty()))
}

pub fn apply(flags: &Flags, probe: &dyn ToolProbe) -> Result<u8, Error> {
    claude_gate()?;
    let mut ctx = context(flags)?;
    for w in &ctx.plan.warnings {
        eprintln!("forge: {w}");
    }
    let mut ch = ctx.changes()?;
    let stuck = !ch.drift.is_empty() || !ch.conflicts.is_empty() || !ch.old_modified.is_empty();
    if stuck && !flags.force {
        let read = |p: &str| std::fs::read_to_string(ctx.base.join(p)).ok();
        for p in &ch.drift {
            eprintln!("forge: {p} was modified since the last apply");
            show_diff(
                read(p).as_deref(),
                ctx.plan.files.get(p).map(String::as_str),
                p,
            );
        }
        for p in &ch.conflicts {
            eprintln!("forge: {p} exists and is not a forge file");
            show_diff(
                read(p).as_deref(),
                ctx.plan.files.get(p).map(String::as_str),
                p,
            );
        }
        for p in &ch.old_modified {
            eprintln!("forge: {p} (generated by forge 0.5) was modified since; apply deletes it");
        }
        eprintln!("forge: stopped. Re-run with --force to overwrite, or move the files away.");
        return Ok(1);
    }
    if flags.dry_run {
        print_diff(&ctx, &ch);
        return Ok(0);
    }
    let mut old: Vec<String> = ch.old_deletes.clone();
    old.extend(ch.old_modified.iter().cloned());
    if !old.is_empty() {
        println!(
            "forge: this repository has the layout of forge 0.5; moving to the new one deletes what forge generated there:"
        );
        for p in &old {
            println!("  {p}");
        }
        println!("  (kept: forge.yaml, .forge/rules/, .forge/packs/)");
        if !confirm("delete them?", flags.yes)? {
            return Err(Error::new("forge: cancelled; nothing written"));
        }
    }
    for s in ch.settings.iter().filter(|s| s.shared) {
        let file = display_path(ctx.level, &ctx.base, &s.file);
        show_diff(Some(&s.before), s.after.as_deref(), &file);
        if !confirm(&format!("apply these changes to {file}?"), flags.yes)? {
            return Err(Error::new("forge: cancelled; nothing written"));
        }
    }
    if offer_ruff_config(&ctx, flags)? {
        ctx = context(flags)?;
        ch = ctx.changes()?;
    }
    if precommit::offer(&mut ctx, flags)? {
        ch = ctx.changes()?;
    }
    write(&ctx, &ch)?;
    install_agents()?;
    if ctx.level == Level::Project {
        provision(&ctx);
    }
    offer_uv_setup(&ctx, flags)?;
    offer_js_setup(&ctx, flags)?;
    for o in &ch.overridden {
        eprintln!("forge: {o}");
    }
    if ch.any() {
        println!(
            "forge: applied ({} written, {} deleted, {} settings file(s) updated)",
            ch.writes.len() + ch.blocks.len(),
            ch.deletes.len() + ch.old_deletes.len(),
            ch.settings.len()
        );
    } else {
        println!("forge: up to date");
    }
    report(&ctx, probe);
    Ok(0)
}

/// Offers the uv setup the active rules ask of the project, where it lacks it: uv's cooldown in
/// `pyproject.toml` (`python/uv/exclude-newer`), and a `uv.lock` matching it
/// (`python/uv/lock-sync`), which `uv lock` creates or updates after the cooldown changed what
/// resolves. Setup is the person's, accepted here; the agent is never sent to add it (a change is
/// held only to what it broke, §10.5). Without a terminal and without `--yes`, it is left for
/// `forge status` to report.
fn offer_uv_setup(ctx: &Ctx, flags: &Flags) -> Result<(), Error> {
    let active = |id: &str| ctx.plan.active.iter().any(|st| st.rule.id == id);
    if ctx.level != Level::Project || ctx.base.join("uv.toml").is_file() {
        return Ok(());
    }
    let path = ctx.base.join("pyproject.toml");
    let Some(before) = std::fs::read_to_string(&path).ok() else {
        return Ok(());
    };
    let cooldown = if active("python/uv/exclude-newer") {
        with_uv_cooldown(&before)
    } else {
        None
    };
    let no_lock = !ctx.base.join("uv.lock").is_file();
    let lock = active("python/uv/lock-sync") && (no_lock || cooldown.is_some());
    if cooldown.is_none() && !lock {
        return Ok(());
    }
    let what = match (&cooldown, lock, no_lock) {
        (Some(_), true, true) => {
            "add uv's cooldown to pyproject.toml and create uv.lock with `uv lock`"
        }
        (Some(_), true, false) => {
            "add uv's cooldown to pyproject.toml and update uv.lock with `uv lock`"
        }
        (Some(_), false, _) => "add uv's cooldown to pyproject.toml",
        (None, _, _) => "create uv.lock with `uv lock`",
    };
    if !flags.yes && !std::io::stdin().is_terminal() {
        println!("forge: the project's uv setup is incomplete; re-run with --yes to {what}");
        return Ok(());
    }
    if let Some(after) = &cooldown {
        show_diff(Some(&before), Some(after), "pyproject.toml");
    }
    if !confirm(
        &format!("{what} (uv then resolves only versions published at least 7 days ago)?"),
        flags.yes,
    )? {
        return Ok(());
    }
    let mut done = Vec::new();
    if let Some(after) = &cooldown {
        write_text(&path, after, false)?;
        done.push("pyproject.toml: added [tool.uv] exclude-newer and required-version".to_string());
    }
    if lock {
        let out = std::process::Command::new("uv")
            .args(["lock", "--quiet"])
            .current_dir(&ctx.base)
            .stdin(std::process::Stdio::null())
            .output();
        match out {
            Ok(o) if o.status.success() => done.push(format!(
                "uv.lock {}",
                if no_lock { "created" } else { "updated" }
            )),
            Ok(o) => {
                let err = String::from_utf8_lossy(&o.stderr);
                let why = err
                    .lines()
                    .rev()
                    .find(|l| !l.trim().is_empty())
                    .unwrap_or("")
                    .trim();
                println!(
                    "forge: uv lock failed ({why}); run it yourself once pyproject.toml resolves"
                );
            }
            Err(e) => println!("forge: uv lock could not run ({e}); run it yourself"),
        }
    }
    if !done.is_empty() {
        println!("forge: {}; commit them with Forge's files", done.join(", "));
    }
    Ok(())
}

/// Offers a ruff config of the project's where the Python checks run and the project has none:
/// Forge's own ruff only lints such a project (§11.2); with the project's config, ruff also
/// formats it and applies its safe fixes after an edit. The config is the active pack's `init/`
/// template, as `forge init` writes it. Without a terminal and without `--yes`, it is left to the
/// person. Returns whether it was created (the plan changes: ruff is configured).
fn offer_ruff_config(ctx: &Ctx, flags: &Flags) -> Result<bool, Error> {
    const RUFF: &str = "ruff.toml";
    let active = |id: &str| ctx.plan.active.iter().any(|st| st.rule.id == id);
    if ctx.level != Level::Project
        || flags.dry_run
        || !(active("python/lint") || active("python/format"))
        || forge_detect::place::ruff_config(&ctx.base, &ctx.base)
    {
        return Ok(false);
    }
    let template = ctx.plan.packs.iter().find_map(|pk| {
        let pack = &ctx.set.packs[&pk.id];
        let dir = pack.init_dir.as_ref()?;
        init_files(pack.source, &ctx.base, dir)
            .into_iter()
            .find(|(rel, _)| rel == RUFF)
            .map(|(_, bytes)| (pk.id.clone(), bytes))
    });
    let Some((pack, bytes)) = template else {
        return Ok(false);
    };
    let what = "the project does not configure ruff, so Forge's ruff lints its Python files but does not format them or apply safe fixes";
    if !flags.yes && !std::io::stdin().is_terminal() {
        println!("forge: {what}; re-run with --yes to create {RUFF}");
        return Ok(false);
    }
    if !confirm(&format!("{what}; create {RUFF} (from {pack})?"), flags.yes)? {
        return Ok(false);
    }
    let template = String::from_utf8_lossy(&bytes).into_owned();
    let text = ruff_file(ctx, &template).unwrap_or(template);
    write_text(&ctx.base.join(RUFF), &text, false)?;
    println!("forge: created {RUFF} (from {pack}); commit it with Forge's files");
    Ok(true)
}

/// Offers the setup the active rules of the project's JavaScript package manager ask of it, where
/// it lacks it, as [`offer_uv_setup`] does for uv: the cooldown settings
/// (`typescript/<pm>/release-age`, [`forge_builtins_code::cooldown::setup`]), and a lock
/// (`typescript/<pm>/lock-sync`): created when the project has none, and updated when the
/// cooldown changed package.json and the lock no longer matches it. Without a terminal and
/// without `--yes`, it is left for `forge status` to report.
fn offer_js_setup(ctx: &Ctx, flags: &Flags) -> Result<(), Error> {
    use forge_check::builtins::{AdapterTools, BuiltinTools, ToolRun};
    let active = |id: String| ctx.plan.active.iter().any(|st| st.rule.id == id);
    if ctx.level != Level::Project {
        return Ok(());
    }
    let Some(pm) = ["npm", "pnpm", "yarn", "bun"].into_iter().find(|pm| {
        active(format!("typescript/{pm}/release-age"))
            || active(format!("typescript/{pm}/lock-sync"))
    }) else {
        return Ok(());
    };
    let Some(lock) = forge_builtins_data::lock::js(pm) else {
        return Ok(());
    };
    let read = |f: &str| std::fs::read_to_string(ctx.base.join(f)).ok();
    let edits = if active(format!("typescript/{pm}/release-age")) {
        forge_builtins_code::cooldown::setup(pm, &read)
    } else {
        Vec::new()
    };
    let has_lock = lock.files.iter().any(|f| ctx.base.join(f).is_file());
    let create = active(format!("typescript/{pm}/lock-sync"))
        && !has_lock
        && ctx.base.join("package.json").is_file();
    if edits.is_empty() && !create {
        return Ok(());
    }
    let files: Vec<&str> = edits.iter().map(|e| e.file).collect();
    let cooldown = format!("add {pm}'s cooldown to {}", files.join(" and "));
    let what = match (edits.is_empty(), create) {
        (false, true) => format!(
            "{cooldown} and create {} with `{}`",
            lock.default, lock.command
        ),
        (false, false) => cooldown,
        (true, _) => format!("create {} with `{}`", lock.default, lock.command),
    };
    if !flags.yes && !std::io::stdin().is_terminal() {
        println!("forge: the project's {pm} setup is incomplete; re-run with --yes to {what}");
        return Ok(());
    }
    for e in &edits {
        show_diff(read(e.file).as_deref(), Some(&e.text), e.file);
    }
    let question = if edits.is_empty() {
        format!("{what}?")
    } else {
        format!("{what} ({pm} then installs only versions published at least 7 days ago)?")
    };
    if !confirm(&question, flags.yes)? {
        return Ok(());
    }
    let mut done = Vec::new();
    for e in &edits {
        write_text(&ctx.base.join(e.file), &e.text, false)?;
        done.push(format!("{}: added {}", e.file, e.added));
    }
    let tools = AdapterTools::new(
        crate::provisioning::builtin_tools(),
        forge_tools::lock_pins(),
    );
    let base = ctx.base.as_path();
    // a lock the cooldown's package.json change left behind is updated too
    let stale = has_lock
        && files.contains(&"package.json")
        && active(format!("typescript/{pm}/lock-sync"))
        && matches!(tools.run(base, base, pm, "lock-check", &[]), ToolRun::Ran(o) if o.status != 0);
    if create || stale {
        match tools.run(base, base, pm, "lock", &[]) {
            ToolRun::Ran(o) if o.status == 0 => done.push(format!(
                "{} {}",
                lock.files
                    .iter()
                    .find(|f| base.join(f).is_file())
                    .unwrap_or(&lock.default),
                if create { "created" } else { "updated" }
            )),
            ToolRun::Ran(o) => {
                let why = o
                    .stderr
                    .lines()
                    .rev()
                    .find(|l| !l.trim().is_empty())
                    .unwrap_or("")
                    .trim();
                println!(
                    "forge: `{}` failed ({why}); run it yourself once package.json resolves",
                    lock.command
                );
            }
            ToolRun::Missing(why) | ToolRun::Unsupported(why) => {
                println!(
                    "forge: `{}` could not run ({why}); run it yourself",
                    lock.command
                )
            }
        }
    }
    if !done.is_empty() {
        println!("forge: {}; commit them with Forge's files", done.join(", "));
    }
    Ok(())
}

/// Installs the tools the lock pins that this setup uses: uv (Forge's PATH directory for the
/// agent) and the pinned tools the active checks and the types engine run. For the person.
fn provision(ctx: &Ctx) {
    let mut names = vec!["uv".to_string()];
    names.extend(forge_check::probe::pinned_tools(&ctx.plan));
    let report = crate::provisioning::ensure_tools(&names);
    let installed: Vec<String> = report
        .tools
        .iter()
        .filter(|t| t.installed_now)
        .map(|t| format!("{} {}", t.name, t.version))
        .collect();
    if !installed.is_empty() {
        println!("forge: installed {}", installed.join(", "));
    }
    for n in &report.notes {
        println!("forge: note: {n}");
    }
    // On a first apply, uv was not in Forge's PATH directory when main put it on PATH.
    crate::provisioning::use_forge_path();
}

/// Forge's own agents (the workflow step and the reviewer) in Claude Code's user config
/// directory, with `FORGE_REVIEW_MODEL` as their model when it is set and `FORGE_REVIEW_EFFORT` as
/// their effort (else medium); rewritten when they differ.
fn install_agents() -> Result<(), Error> {
    let dir = super::claude_config_dir()?;
    let model = std::env::var("FORGE_REVIEW_MODEL").ok();
    let effort = std::env::var("FORGE_REVIEW_EFFORT").ok();
    let written =
        forge_hooks::agents::install(&dir, model.as_deref(), effort.as_deref()).map_err(|e| {
            Error::new(format!(
                "forge: cannot write Claude Code's agents in {}: {e}",
                dir.display()
            ))
        })?;
    if !written.is_empty() {
        println!(
            "forge: wrote its agents in {}",
            dir.join("agents").display()
        );
    }
    Ok(())
}

fn write(ctx: &Ctx, ch: &Changes) -> Result<(), Error> {
    let base = &ctx.base;
    for w in &ch.writes {
        let exec = w.path.ends_with("/pre-commit") && w.after.starts_with("#!");
        write_text(&base.join(&w.path), &w.after, exec)?;
    }
    for b in &ch.blocks {
        let yaml = b.path.ends_with(".yml") || b.path.ends_with(".yaml");
        write_text(&base.join(&b.path), &b.after, b.created && !yaml)?;
    }
    for d in &ch.deletes {
        delete_path(base, d)?;
    }
    for s in &ch.settings {
        write_settings(base, &s.file, s.after.as_deref())?;
    }
    if !ch.old_modified.is_empty() || !ch.old_deletes.is_empty() {
        for d in ch.old_modified.iter().chain(&ch.old_deletes) {
            delete_path(base, d)?;
        }
    }
    write_text(&base.join(&ctx.plan.lock_path), &ch.lock_text, false)?;
    if ctx.level == Level::Project {
        prune_dirs(&base.join(".forge"), base);
    }
    Ok(())
}

/// What apply tells the person after writing: audits, the commit-time check, missing tools,
/// what tool versions cannot do, notes. Machine state: never in the rules files.
fn report(ctx: &Ctx, probe: &dyn ToolProbe) {
    if ctx.level == Level::Project {
        let audits = audit_rules(&ctx.plan, probe);
        let unsatisfied: Vec<_> = audits
            .iter()
            .filter(|a| a.status == forge_render::report::AuditStatus::Unsatisfied)
            .collect();
        if !unsatisfied.is_empty() {
            println!("{}", format_audits(unsatisfied));
        }
        let pre = precommit::state(ctx);
        if pre.activate.is_some() {
            println!("forge: pre-commit: {}", precommit::not_checked(ctx, &pre));
        } else if !pre.installed {
            println!(
                "forge: pre-commit: not installed, so commits are not checked; {}",
                precommit::hint(ctx)
            );
        }
    }
    let missing = probe.missing_tools(&ctx.plan);
    if !missing.is_empty() {
        println!(
            "forge: missing tools (checks using them are skipped): {}",
            missing.join(", ")
        );
    }
    let versions = probe.tool_versions(&ctx.plan);
    if !versions.is_empty() {
        println!("forge: tool versions (what they cannot do is not enforced):");
        for v in versions {
            println!("  {v}");
        }
    }
    for n in person_notes(ctx, probe) {
        println!("forge: note: {n}");
    }
}

/// `forge init`: the active packs' `init/` templates that do not exist yet, then apply.
pub fn init(flags: &Flags, probe: &dyn ToolProbe) -> Result<u8, Error> {
    if flags.user {
        return Err(Error::usage("forge: init is project-level only"));
    }
    claude_gate()?;
    let ctx = context(flags)?;
    if ctx.lock.is_some() || ctx.migration.is_some() {
        return Err(Error::new(
            "forge: init is for new projects; this one already has forge (use forge apply)",
        ));
    }
    for pk in &ctx.plan.packs {
        let pack = &ctx.set.packs[&pk.id];
        let Some(dir) = &pack.init_dir else { continue };
        for (rel, bytes) in init_files(pack.source, &ctx.base, dir) {
            let dest = ctx.base.join(&rel);
            if dest.exists() {
                println!("forge: {rel} exists, kept");
            } else if flags.dry_run {
                println!("forge: would create {rel} (from {})", pk.id);
            } else {
                let text = String::from_utf8_lossy(&bytes).into_owned();
                let text = if rel == "ruff.toml" {
                    ruff_file(&ctx, &text).unwrap_or(text)
                } else {
                    text
                };
                let text = switch_offs(&rel, &text, &ctx).unwrap_or(text);
                write_text(&dest, &text, false)?;
                println!("forge: created {rel} (from {})", pk.id);
            }
        }
    }
    apply(flags, probe)
}

/// A ruff.toml from the pack's template with what the active `tool: ruff` targets' snippets need
/// (the codes they expect, their settings), so every such rule is enforced by the file.
fn ruff_file(ctx: &Ctx, template: &str) -> Option<String> {
    use forge_packs::model::{AuditedTool, Target};
    let snippets: Vec<&str> = ctx
        .plan
        .active
        .iter()
        .flat_map(|st| st.rule.enforce.iter())
        .filter_map(|t| match t {
            Target::Tool(t) if t.tool == AuditedTool::Ruff => Some(t.snippet.as_str()),
            _ => None,
        })
        .collect();
    forge_check::ruff_config::file_config(template, snippets)
}

/// The files of an `init/` directory: path below it → content, sorted.
fn init_files(source: PackSource, base: &std::path::Path, dir: &str) -> Vec<(String, Vec<u8>)> {
    let mut out = Vec::new();
    match source {
        PackSource::Builtin => {
            fn walk(d: &include_dir::Dir<'static>, root: &str, out: &mut Vec<(String, Vec<u8>)>) {
                for f in d.files() {
                    let p = f.path().to_string_lossy().replace('\\', "/");
                    if let Some(rel) = p.strip_prefix(root) {
                        out.push((rel.to_string(), f.contents().to_vec()));
                    }
                }
                for sub in d.dirs() {
                    walk(sub, root, out);
                }
            }
            if let Some(d) = forge_packs::BUILTIN_PACKS.get_dir(dir) {
                walk(d, &format!("{dir}/"), &mut out);
            }
        }
        PackSource::Local => {
            fn walk(d: &std::path::Path, rel: &str, out: &mut Vec<(String, Vec<u8>)>) {
                let Ok(rd) = std::fs::read_dir(d) else { return };
                for e in rd.flatten() {
                    let name = e.file_name().to_string_lossy().into_owned();
                    let r = if rel.is_empty() {
                        name
                    } else {
                        format!("{rel}/{name}")
                    };
                    if e.path().is_dir() {
                        walk(&e.path(), &r, out);
                    } else if let Ok(b) = std::fs::read(e.path()) {
                        out.push((r, b));
                    }
                }
            }
            walk(&base.join(dir), "", &mut out);
        }
    }
    out.sort();
    out
}

/// An init template with the diagnostics active packs switch off set to "off" (Biome's
/// `linter.rules.<group>.<name>`); `None` when none concerns it.
fn switch_offs(file: &str, text: &str, ctx: &Ctx) -> Option<String> {
    let name = file.rsplit('/').next().unwrap_or(file);
    if name != "biome.json" && name != "biome.jsonc" {
        return None;
    }
    let mine: Vec<_> = ctx
        .plan
        .switched_off
        .iter()
        .filter(|o| o.tool == "biome")
        .collect();
    if mine.is_empty() {
        return None;
    }
    let mut out = text.to_string();
    for o in mine {
        let parts: Vec<&str> = o.expects.split('/').collect();
        if parts.len() < 3 {
            continue;
        }
        out = forge_render::settings::set_value(
            &out,
            &["linter", "rules", parts[1], parts[2]],
            &serde_json::Value::String("off".into()),
        )
        .ok()?;
    }
    Some(out)
}
