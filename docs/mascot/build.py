"""Build forge-intro.sh (CLI) and forge-mascot.js (website) from mascot.frames.

mascot.frames holds pixel grids ('#' filled, '.' empty). Every 2 pixel rows
become 1 terminal line of half-block characters, so pixels come out square.
"""
import json
from pathlib import Path

here = Path(__file__).parent

# ---- parse
frames, blink, cur = [], None, None
for raw in (here / "mascot.frames").read_text(encoding="utf-8").splitlines():
    line = raw.rstrip()
    if line.startswith("#") and not set(line) <= {"#", "."}:
        continue  # comment (pixel rows contain only '#' and '.')
    if not line:
        continue
    if line.startswith("@"):
        arg = line[1:].strip()
        cur = {"t": 0.0, "px": []}
        if arg == "blink":
            blink = cur
        else:
            cur["t"] = float(arg or 0)
            frames.append(cur)
        continue
    if cur is None:
        continue
    cur["px"].append(line)

if not frames:
    raise SystemExit("No frames found.")
if blink is None:
    raise SystemExit("Missing '@ blink' frame (the final logo with eyes closed).")
size = (len(frames[0]["px"]), max(len(r) for r in frames[0]["px"]))
for i, f in enumerate(frames + [blink]):
    name = "blink" if f is blink else f"frame {i + 1}"
    if len(f["px"]) != size[0]:
        raise SystemExit(f"{name} has {len(f['px'])} pixel rows, expected {size[0]}.")
    if any(set(r) - {"#", "."} for r in f["px"]):
        raise SystemExit(f"{name} uses characters other than '#' and '.'.")

def render(px):
    rows = [r.ljust(size[1], ".") for r in px]
    if len(rows) % 2:
        rows.append("." * size[1])
    out = []
    for a, b in zip(rows[0::2], rows[1::2]):
        out.append("".join(
            "█" if x == "#" and y == "#" else "▀" if x == "#" else "▄" if y == "#" else " "
            for x, y in zip(a, b)).rstrip())
    return out

for f in frames + [blink]:
    f["l"] = render(f["px"])
H = len(frames[0]["l"])
logo, shut = frames[-1]["l"], blink["l"]

def heredoc(lines):
    return "<<'FRAME'\n" + "\n".join(lines) + "\nFRAME\n"

# ---- CLI: POSIX sh
sh = f"""#!/bin/sh
# Forge mascot intro. Generated by build.py from mascot.frames; edit that file instead.
#
# FORGE_COLOR   optional ANSI color code, e.g. 33. Unset = terminal default.
# FORGE_HOLD    seconds to keep the mascot blinking after the intro (default 3).
#               0 = exit right away, -1 = blink until Ctrl-C.
# FORGE_STATIC  1 = print the final logo only. Also automatic when output is not a terminal.
set -u
esc=$(printf '\\033')
if [ -n "${{FORGE_COLOR:-}}" ]; then on="${{esc}}[${{FORGE_COLOR}}m"; off="${{esc}}[0m"; else on=""; off=""; fi

logo() {{
cat {heredoc(logo)}}}
shut() {{
cat {heredoc(shut)}}}

if [ "${{FORGE_STATIC:-0}}" = 1 ] || [ ! -t 1 ]; then printf '%s' "$on"; logo; printf '%s' "$off"; exit 0; fi

printf '%s[?25l' "$esc"
trap 'printf "%s[?25h%s" "$esc" "$off"' EXIT
trap 'exit 130' INT TERM
printf '%s' "$on"
first=1
show() {{
  [ "$first" = 1 ] || printf '%s[{H}A' "$esc"
  first=0
  while IFS= read -r l; do printf '%s[2K%s\\n' "$esc" "$l"; done
}}
"""
for f in frames:
    sh += "show " + heredoc(f["l"])
    if f["t"]:
        sh += f"sleep {f['t']:g}\n"
sh += """
# Random blinking: wait 1.5-5 s, blink for 0.12 s, sometimes blink twice.
hold=${FORGE_HOLD:-3}
n=0
rnd() { # prints "<wait seconds> <double 0|1>"
  n=$((n + 1))
  awk -v s="$(( $(date +%s) % 100000 + $$ * 7 + n * 131 ))" \\
    'BEGIN { srand(s); printf "%.2f %d\\n", 1.5 + rand() * 3.5, (rand() < 0.2) }'
}
left_ms=$(awk -v h="$hold" 'BEGIN { printf "%d", h * 1000 }')
while [ "$hold" = -1 ] || [ "$left_ms" -gt 0 ]; do
  set -- $(rnd)
  wait_ms=$(awk -v w="$1" 'BEGIN { printf "%d", w * 1000 }')
  if [ "$hold" != -1 ] && [ "$wait_ms" -ge "$left_ms" ]; then
    sleep "$(awk -v m="$left_ms" 'BEGIN { printf "%.2f", m / 1000 }')"; break
  fi
  sleep "$1"
  shut | show; sleep 0.12; logo | show
  if [ "$2" = 1 ]; then sleep 0.15; shut | show; sleep 0.1; logo | show; fi
  left_ms=$((left_ms - wait_ms - 120))
done
printf '%s' "$off"
"""
(here / "forge-intro.sh").write_text(sh, encoding="utf-8")
(here / "forge-intro.sh").chmod(0o755)
(here / "forge-logo.txt").write_text("\n".join(logo) + "\n", encoding="utf-8")

# ---- Website: framework-free custom element <forge-mascot>
data = json.dumps({"frames": [[f["t"], "\n".join(f["l"])] for f in frames],
                   "blink": "\n".join(shut)}, ensure_ascii=False)
js = """// <forge-mascot>: generated by build.py from mascot.frames; edit that file instead.
// Attributes: static (skip the intro), loop (replay the intro), no-blink, label="..." (accessible name).
// Click or press Enter/Space to replay. With reduced motion: logo only, no blinking.
const DATA = __DATA__;
const LOGO = DATA.frames[DATA.frames.length - 1][1];

class ForgeMascot extends HTMLElement {
  connectedCallback() {
    if (this._pre) return;
    const root = this.attachShadow({ mode: "open" });
    root.innerHTML = `<style>
      :host { display: inline-block; color: inherit; cursor: pointer; }
      :host(:focus-visible) { outline: 2px solid currentColor; outline-offset: 4px; }
      pre { margin: 0; font: inherit; line-height: 1; white-space: pre; letter-spacing: 0;
            font-family: var(--forge-mascot-font, ui-monospace, "SFMono-Regular", Menlo, Consolas, "DejaVu Sans Mono", monospace); }
    </style><pre aria-hidden="true"></pre>`;
    this._pre = root.querySelector("pre");
    this.setAttribute("role", "img");
    if (!this.hasAttribute("aria-label")) this.setAttribute("aria-label", this.getAttribute("label") || "Forge mascot");
    if (!this.hasAttribute("tabindex")) this.tabIndex = 0;
    this.addEventListener("click", () => this.play());
    this.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); this.play(); }
    });
    this._reduced = window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
    if (this.hasAttribute("static") || this._reduced) this._idle(); else this.play();
  }
  disconnectedCallback() { this._stop(); }
  _stop() { clearTimeout(this._t); clearTimeout(this._b); }
  _set(text) { this._pre.textContent = text; }
  play() {
    this._stop();
    let i = 0;
    const tick = () => {
      this._set(DATA.frames[i][1]);
      if (i < DATA.frames.length - 1) { this._t = setTimeout(tick, DATA.frames[i][0] * 1000); i++; }
      else if (this.hasAttribute("loop")) { this._blinks(); this._t = setTimeout(() => this.play(), 6000); }
      else this._blinks();
    };
    tick();
  }
  _idle() { this._stop(); this._set(LOGO); this._blinks(); }
  _blinks() {
    if (this._reduced || this.hasAttribute("no-blink")) return;
    const once = (then) => {
      this._set(DATA.blink);
      this._b = setTimeout(() => { this._set(LOGO); then(); }, 120);
    };
    const next = () => {
      this._b = setTimeout(() => {
        if (Math.random() < 0.2) once(() => { this._b = setTimeout(() => once(next), 150); });
        else once(next);
      }, 1500 + Math.random() * 3500);
    };
    next();
  }
}
if (!customElements.get("forge-mascot")) customElements.define("forge-mascot", ForgeMascot);
""".replace("__DATA__", data)
(here.parent / "src" / "components" / "forge-mascot.js").write_text(js, encoding="utf-8")

# ---- Website: static logo and favicon from the final frame's pixels
px = frames[-1]["px"]
cols = [i for i in range(size[1]) if any(i < len(r) and r[i] == "#" for r in px)]
x0, w = min(cols), max(cols) + 1 - min(cols)
def rects(ox, oy):
    out = []
    for y, row in enumerate(px):
        row = row.ljust(size[1], ".")[x0:x0 + w]
        x = 0
        while x < w:
            if row[x] == "#":
                s0 = x
                while x < w and row[x] == "#":
                    x += 1
                out.append(f'<rect x="{s0 + ox}" y="{y + oy}" width="{x - s0}" height="1"/>')
            else:
                x += 1
    return "".join(out)
public = here.parent / "public"
(public / "logo.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {size[0]}" shape-rendering="crispEdges" role="img" aria-label="Forge">'
    f'<g fill="#ea580c">{rects(0, 0)}</g></svg>\n', encoding="utf-8")
side = max(w, size[0]) + 2
(public / "favicon.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {side} {side}" shape-rendering="crispEdges">'
    f'<rect width="{side}" height="{side}" rx="3" fill="#1c1917"/><g fill="#f97316">{rects((side - w) // 2, (side - size[0]) // 2)}</g></svg>\n',
    encoding="utf-8")
print(f"Built {len(frames)} frames + blink, {size[1]} columns x {H} lines.")
